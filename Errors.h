#pragma once
#include <QString>

// Единый справочник кодов состояний/ошибок.
// Все пользовательские тексты — ТОЛЬКО здесь; в коде ссылаемся на коды,
// чтобы не плодить дубли строк по исходникам.
namespace Err {

enum Code {
    // 1xxx — камеры/потоки
    CamConnecting  = 1001,   // идёт подключение к потоку камеры
    CamUnavailable = 1002,   // камера недоступна (поток не открывается)
    CamNoSignal    = 1003,   // поток открыт, но кадры не идут

    // 2xxx — устройства (регистраторы)
    DevUnreachable = 2001,   // регистратор недоступен (нет связи)
    DevAuthFailed  = 2002,   // неверный логин или пароль
};

QString text(int code);       // текст без кода
QString withCode(int code);   // "текст (E1002)" — для показа пользователю

}
